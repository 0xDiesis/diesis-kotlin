# --- Keccak-256 (the pre-NIST padding Ethereum uses; hashlib.sha3_256 differs)

_ROUND_CONSTANTS = [
    0x0000000000000001, 0x0000000000008082, 0x800000000000808A, 0x8000000080008000,
    0x000000000000808B, 0x0000000080000001, 0x8000000080008081, 0x8000000000008009,
    0x000000000000008A, 0x0000000000000088, 0x0000000080008009, 0x000000008000000A,
    0x000000008000808B, 0x800000000000008B, 0x8000000000008089, 0x8000000000008003,
    0x8000000000008002, 0x8000000000000080, 0x000000000000800A, 0x800000008000000A,
    0x8000000080008081, 0x8000000000008080, 0x0000000080000001, 0x8000000080008008,
]
_ROTATIONS = [
    [0, 36, 3, 41, 18],
    [1, 44, 10, 45, 2],
    [62, 6, 43, 15, 61],
    [28, 55, 25, 21, 56],
    [27, 20, 39, 8, 14],
]
_MASK = (1 << 64) - 1


def _rotl(value: int, shift: int) -> int:
    return ((value << shift) | (value >> (64 - shift))) & _MASK if shift else value


def _keccak_f(state: list[list[int]]) -> None:
    for constant in _ROUND_CONSTANTS:
        c = [state[x][0] ^ state[x][1] ^ state[x][2] ^ state[x][3] ^ state[x][4] for x in range(5)]
        d = [c[(x - 1) % 5] ^ _rotl(c[(x + 1) % 5], 1) for x in range(5)]
        for x in range(5):
            for y in range(5):
                state[x][y] ^= d[x]
        b = [[0] * 5 for _ in range(5)]
        for x in range(5):
            for y in range(5):
                b[y][(2 * x + 3 * y) % 5] = _rotl(state[x][y], _ROTATIONS[x][y])
        for x in range(5):
            for y in range(5):
                state[x][y] = b[x][y] ^ ((~b[(x + 1) % 5][y]) & b[(x + 2) % 5][y])
        state[0][0] ^= constant


def keccak256(data: bytes) -> bytes:
    rate = 136
    padded = bytearray(data)
    padded.append(0x01)
    while len(padded) % rate:
        padded.append(0)
    padded[-1] |= 0x80
    state = [[0] * 5 for _ in range(5)]
    for offset in range(0, len(padded), rate):
        block = padded[offset : offset + rate]
        for i in range(rate // 8):
            lane = int.from_bytes(block[8 * i : 8 * i + 8], "little")
            state[i % 5][i // 5] ^= lane
        _keccak_f(state)
    out = b"".join(state[i % 5][i // 5].to_bytes(8, "little") for i in range(4))
    return out[:32]


def checksum_address(address: str) -> str:
    """Return the EIP-55 checksummed form of a 0x-prefixed address."""
    lower = address.lower().removeprefix("0x")
    if not re.fullmatch(r"[0-9a-f]{40}", lower):
        raise ValueError(f"invalid address: {address}")
    digest = keccak256(lower.encode("ascii")).hex()
    return "0x" + "".join(
        ch.upper() if ch.isalpha() and int(digest[i], 16) >= 8 else ch
        for i, ch in enumerate(lower)
    )


# --- Kotlin rendering


def kotlin_string(value: str) -> str:
    return json.dumps(value)


def render_addresses(canonical: dict) -> str:
    lines = [
        HEADER,
        "package xyz.diesis\n",
        "\n",
        "/**\n",
        " * System contract and precompile addresses, as EIP-55 checksummed strings.\n",
        " *\n",
        " * Each constant is a `public static final String` field when used from Java.\n",
        " */\n",
        "public object DiesisAddresses {\n",
    ]
    for name, address in canonical["addresses"].items():
        lines.append(f"    public const val {name}: String = {kotlin_string(checksum_address(address))}\n")
    lines.append("\n")
    lines.append("    /** Every address above, keyed by constant name, in `canonical.json` order. */\n")
    lines.append("    @JvmField\n")
    lines.append("    public val ALL: Map<String, String> = linkedMapOf(\n")
    for name in canonical["addresses"]:
        lines.append(f"        {kotlin_string(name)} to {name},\n")
    lines.append("    )\n")
    lines.append("}\n")
    return "".join(lines)


def render_chain(chain: dict) -> str:
    currency = chain["nativeCurrency"]
    return (
        "DiesisChain(\n"
        f"        id = {chain['id']}L,\n"
        f"        name = {kotlin_string(chain['name'])},\n"
        "        nativeCurrency = NativeCurrency(\n"
        f"            name = {kotlin_string(currency['name'])},\n"
        f"            symbol = {kotlin_string(currency['symbol'])},\n"
        f"            decimals = {currency['decimals']},\n"
        "        ),\n"
        f"        rpcUrl = {kotlin_string(chain['rpcUrl'])},\n"
        f"        explorerUrl = {kotlin_string(chain['explorerUrl'])},\n"
        f"        testnet = {'true' if chain['testnet'] else 'false'},\n"
        "    )"
    )


def render_chains(canonical: dict) -> str:
    chains = canonical["chains"]
    if set(chains) != {"mainnet", "testnet"}:
        raise ValueError(f"unexpected chains in canonical.json: {sorted(chains)}")
    return (
        HEADER
        + "package xyz.diesis\n"
        + "\n"
        + "/** Diesis network definitions. */\n"
        + "public object DiesisChains {\n"
        + "    /** Diesis mainnet. */\n"
        + "    @JvmField\n"
        + f"    public val diesis: DiesisChain = {render_chain(chains['mainnet'])}\n"
        + "\n"
        + "    /** Diesis testnet. */\n"
        + "    @JvmField\n"
        + f"    public val diesisTestnet: DiesisChain = {render_chain(chains['testnet'])}\n"
        + "\n"
        + "    /** Both networks, mainnet first. */\n"
        + "    @JvmField\n"
        + "    public val ALL: List<DiesisChain> = listOf(diesis, diesisTestnet)\n"
        + "}\n"
    )


def render_contracts(canonical: dict) -> str:
    fixed = [(key, contract, address) for key, contract, address in PUBLIC_CONTRACTS if address]
    for _, _, address in fixed:
        if address not in canonical["addresses"]:
            raise ValueError(f"{address} is missing from canonical.json")
    lines = [HEADER, "package xyz.diesis\n", "\n"]
    for contract in sorted({contract for _, contract, _ in fixed}):
        lines.append(f"import {BINDINGS_PACKAGE}.{contract}\n")
    lines += [
        "\n",
        "/**\n",
        " * Every public system contract that lives at a fixed address, keyed like\n",
        " * `diesisContracts` in the TypeScript SDK. The typed argument, event, error,\n",
        " * and tuple classes for each one are nested in the object of the same name in\n",
        " * [xyz.diesis.contracts], such as [DiesisStaking].\n",
        " */\n",
        "public object DiesisContracts {\n",
    ]
    for key, contract, address in fixed:
        lines.append("    @JvmField\n")
        lines.append(
            f"    public val {key}: DiesisContract = DiesisContract({kotlin_string(key)}, "
            f"{kotlin_string(contract)}, DiesisAddresses.{address}, {contract}.JSON)\n"
        )
        lines.append("\n")
    lines.append("    /** Every entry above, in table order. */\n")
    lines.append("    @JvmField\n")
    lines.append("    public val ALL: List<DiesisContract> = listOf(\n")
    for key, _, _ in fixed:
        lines.append(f"        {key},\n")
    lines.append("    )\n")
    lines.append("\n")
    lines.append("    /** Returns the entry with this key, such as `\"staking\"`, or null. */\n")
    lines.append("    @JvmStatic\n")
    lines.append("    public fun byKey(key: String): DiesisContract? = ALL.firstOrNull { it.key == key }\n")
    lines.append("}\n")
    return "".join(lines)


# --- abi-typegen


def check_typegen_version() -> None:
    output = subprocess.run([str(TYPEGEN), "--version"], check=True, capture_output=True, text=True).stdout
    match = re.search(r"(\d+)\.(\d+)\.(\d+)", output)
    if not match or tuple(int(part) for part in match.groups()) < MINIMUM_TYPEGEN:
        wanted = ".".join(map(str, MINIMUM_TYPEGEN))
        raise SystemExit(f"abi-typegen {wanted} or newer is required, found: {output.strip()}")


def generate_bindings() -> dict[str, str]:
    """Run abi-typegen and return {file name: source}."""
    check_typegen_version()
    contracts = ",".join(contract for _, contract, _ in PUBLIC_CONTRACTS)
    with tempfile.TemporaryDirectory(prefix="diesis-kotlin-") as temp:
        subprocess.run(
            [
                str(TYPEGEN),
                "generate",
                "--artifacts",
                str(CONTRACTS_DIR / "out"),
                "--out",
                temp,
                "--target",
                "kotlin",
                "--package",
                BINDINGS_PACKAGE,
                "--contracts",
                contracts,
            ],
            check=True,
            stdout=subprocess.DEVNULL,
        )
        produced = sorted(Path(temp).glob("*.kt"))
        names = {path.stem for path in produced}
        expected = {contract for _, contract, _ in PUBLIC_CONTRACTS}
        if names != expected:
            raise SystemExit(f"abi-typegen output mismatch: missing {sorted(expected - names)}, extra {sorted(names - expected)}")
        return {path.name: path.read_text(encoding="utf-8") for path in produced}


def expected_files() -> dict[Path, str]:
    canonical = json.loads(CANONICAL.read_text(encoding="utf-8"))
    if canonical.get("schemaVersion") != 1:
        raise SystemExit(f"unsupported canonical.json schemaVersion: {canonical.get('schemaVersion')}")
    files: dict[Path, str] = {
        KOTLIN_ROOT / "DiesisAddresses.kt": render_addresses(canonical),
        KOTLIN_ROOT / "DiesisChains.kt": render_chains(canonical),
        KOTLIN_ROOT / "DiesisContracts.kt": render_contracts(canonical),
    }
    for name, source in generate_bindings().items():
        files[BINDINGS_DIR / name] = source
    return files


def main(argv: list[str]) -> int:
    if argv not in ([], ["--check"]):
        print("usage: generate.py [--check]", file=sys.stderr)
        return 2
    check = argv == ["--check"]
    stale: list[str] = []

    if SDK_CANONICAL.exists():
        source = SDK_CANONICAL.read_bytes()
        if not CANONICAL.exists() or CANONICAL.read_bytes() != source:
            if check:
                stale.append("canonical.json (differs from ../diesis-js/canonical.json)")
            else:
                CANONICAL.write_bytes(source)
    elif check:
        print(f"warning: {SDK_CANONICAL} not found; skipping canonical.json comparison", file=sys.stderr)

    files = expected_files()
    existing = set(BINDINGS_DIR.glob("*.kt")) if BINDINGS_DIR.exists() else set()
    extra = sorted(existing - set(files))

    for path, content in files.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            if check:
                stale.append(str(path.relative_to(REPO_ROOT)))
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    for path in extra:
        if check:
            stale.append(f"{path.relative_to(REPO_ROOT)} (not produced by the generator)")
        else:
            path.unlink()

    if stale:
        print("generated files are stale; run python3 scripts/generate.py:", file=sys.stderr)
        for entry in stale:
            print(f"  {entry}", file=sys.stderr)
        return 1
    if check:
        print("generated files are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
